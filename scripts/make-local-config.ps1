# 从 .local/settings.json 生成 Spring Boot 本地配置，供 IDEA 直接运行主类使用。
# 生成物 .local/application-local.yml 已被 Git 忽略，包含本机数据库密码和密钥，不要提交。
$ErrorActionPreference='Stop'
$projectRoot=Split-Path -Parent $PSScriptRoot
$settingsPath=Join-Path $projectRoot '.local/settings.json'
$outPath=Join-Path $projectRoot '.local/application-local.yml'
if(-not (Test-Path -LiteralPath $settingsPath)){throw 'Run scripts/setup.ps1 first: .local/settings.json is missing'}
$config=Get-Content -Raw -LiteralPath $settingsPath | ConvertFrom-Json

function Quote-Yaml([string]$value){
  if($null -eq $value){return "''"}
  if($value -match "[\r\n]"){throw 'settings value contains a newline; cannot write single-line YAML'}
  return "'" + ($value -replace "'", "''") + "'"
}
function Need([string]$name){
  $value=$config.$name
  if($null -eq $value -or [string]::IsNullOrWhiteSpace([string]$value)){throw ".local/settings.json is missing $name"}
  return [string]$value
}

$keystore=((Join-Path $projectRoot '.local/localhost.p12') -replace '\\','/')
$uploadDir=((Join-Path $projectRoot '.local/uploads') -replace '\\','/')
$lines=@(
  '# Generated by scripts/make-local-config.ps1 from .local/settings.json.',
  '# Local-only file: never commit it.',
  'spring:',
  '  datasource:',
  "    url: $(Quote-Yaml (Need 'DB_URL'))",
  "    username: $(Quote-Yaml (Need 'DB_USER'))",
  "    password: $(Quote-Yaml (Need 'DB_PASSWORD'))",
  'server:',
  '  ssl:',
  "    key-store: $(Quote-Yaml ('file:' + $keystore))",
  "    key-store-password: $(Quote-Yaml (Need 'TLS_PASSWORD'))",
  'campus:',
  "  crypto-key: $(Quote-Yaml (Need 'APP_CRYPTO_KEY'))",
  "  cursor-key: $(Quote-Yaml (Need 'APP_CURSOR_KEY'))",
  "  upload-dir: $(Quote-Yaml $uploadDir)"
)
Set-Content -LiteralPath $outPath -Value ($lines -join "`r`n") -Encoding utf8
Write-Output "Wrote $outPath"
Write-Output 'IDEA can now run CampusApplication directly; the file is ignored by Git.'
